'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, 'resources/modern/tokens.json');
const cssPath = path.join(root, 'resources/modern/tokens.css');
const tsPath = path.join(root, 'resources/modern/tokens.ts');
const checkOnly = process.argv.includes('--check');
const tokens = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));

const css = `.dcat-modern-active {\n${Object.entries(tokens).map(([name, value]) => `    --dcat-modern-${name}: ${value};`).join('\n')}\n}\n`;
const ts = `// Generated by scripts/view-modernization-tokens.js. Do not edit directly.\nexport const dcatTokens = ${JSON.stringify(tokens, null, 4)} as const;\n\nexport type DcatTokenName = keyof typeof dcatTokens;\n`;

if (checkOnly) {
    verify(cssPath, css);
    verify(tsPath, ts);
    console.log(`Dcat UI tokens OK: ${Object.keys(tokens).length} generated tokens.`);
    process.exit(0);
}

fs.writeFileSync(cssPath, css);
fs.writeFileSync(tsPath, ts);
console.log(`Dcat UI tokens updated: ${Object.keys(tokens).length} generated tokens.`);

function verify(file, expected) {
    if (!fs.existsSync(file)) {
        console.error(`Generated token artifact is missing: ${path.relative(root, file)}`);
        process.exit(1);
    }
    if (fs.readFileSync(file, 'utf8') !== expected) {
        console.error(`Generated token artifact is stale: ${path.relative(root, file)}`);
        process.exit(1);
    }
}
